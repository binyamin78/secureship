"""Generates k8s/grafana-dashboard.yaml (a ConfigMap Grafana loads automatically).

Run: python monitoring/build_dashboard.py
"""
import json
from pathlib import Path

DS = {"type": "prometheus", "uid": "prometheus"}
NS = 'namespace="secureship"'


def panel(pid, title, kind, exprs, x, y, w, h, unit="short", legend=None, extra=None):
    p = {
        "id": pid,
        "title": title,
        "type": kind,
        "datasource": DS,
        "gridPos": {"x": x, "y": y, "w": w, "h": h},
        "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
        "targets": [
            {"refId": chr(65 + i), "datasource": DS, "expr": e, "legendFormat": (legend or [""] * len(exprs))[i]}
            for i, e in enumerate(exprs)
        ],
    }
    if extra:
        p.update(extra)
    return p


panels = [
    panel(1, "Pods running", "stat",
          [f'kube_horizontalpodautoscaler_status_current_replicas{{{NS}, horizontalpodautoscaler="devboard"}}'],
          0, 0, 6, 5, extra={"options": {"colorMode": "background", "graphMode": "area"}}),
    panel(2, "Requests / sec", "stat",
          [f"sum(rate(devboard_http_requests_total{{{NS}}}[1m]))"], 6, 0, 6, 5, unit="reqps"),
    panel(3, "p95 latency", "stat",
          [f"histogram_quantile(0.95, sum by (le) (rate(devboard_http_request_duration_seconds_bucket{{{NS}}}[1m])))"],
          12, 0, 6, 5, unit="s"),
    panel(4, "Firing alerts", "stat",
          ['count(ALERTS{alertstate="firing", alertname=~"DevBoard.*"}) or vector(0)'], 18, 0, 6, 5,
          extra={"fieldConfig": {"defaults": {"unit": "short", "thresholds": {"mode": "absolute", "steps": [
              {"color": "green", "value": None}, {"color": "red", "value": 1}]}}, "overrides": []},
              "options": {"colorMode": "background"}}),
    panel(5, "HPA: current vs desired pods", "timeseries",
          [f'kube_horizontalpodautoscaler_status_current_replicas{{{NS}, horizontalpodautoscaler="devboard"}}',
           f'kube_horizontalpodautoscaler_status_desired_replicas{{{NS}, horizontalpodautoscaler="devboard"}}'],
          0, 5, 12, 8, legend=["current", "desired"]),
    panel(6, "CPU per pod (cores)", "timeseries",
          [f'sum by (pod) (rate(container_cpu_usage_seconds_total{{{NS}, container="devboard"}}[1m]))'],
          12, 5, 12, 8, legend=["{{pod}}"]),
    panel(7, "Requests / sec per pod", "timeseries",
          [f"sum by (pod) (rate(devboard_http_requests_total{{{NS}}}[1m]))"],
          0, 13, 12, 8, unit="reqps", legend=["{{pod}}"]),
    panel(8, "Responses by status code", "timeseries",
          [f"sum by (status) (rate(devboard_http_requests_total{{{NS}}}[1m]))"],
          12, 13, 12, 8, unit="reqps", legend=["{{status}}"]),
]

dashboard = {
    "uid": "secureship",
    "title": "SecureShip - DevBoard",
    "tags": ["secureship"],
    "timezone": "browser",
    "refresh": "5s",
    "time": {"from": "now-15m", "to": "now"},
    "schemaVersion": 39,
    "panels": panels,
}

body = json.dumps(dashboard, indent=2)
yaml = (
    "# Generated by monitoring/build_dashboard.py - do not edit by hand.\n"
    "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: secureship-dashboard\n"
    "  namespace: secureship\n  labels:\n    grafana_dashboard: \"1\"\n"
    "data:\n  secureship.json: |\n" + "\n".join("    " + line for line in body.splitlines()) + "\n"
)
out = Path(__file__).resolve().parent.parent / "k8s" / "grafana-dashboard.yaml"
out.write_text(yaml, encoding="utf-8")
print(f"wrote {out}")
